    print("\\nModel-wise status:")
    print(pd.crosstab(out["model_provider"], out["helpdesk_project_aware_status"]))

    total = len(out)
    passed = (out["helpdesk_project_aware_status"] == "Passed").sum()
    failed = (out["helpdesk_project_aware_status"] == "Failed").sum()

    print("\\nNUMERIC SUMMARY")
    print("=" * 90)
    print("Total HelpDesk compile-passed tests repaired at runtime:", total)
    print("Project-aware runtime passed:", passed)
    print("Project-aware runtime failed:", failed)

    if total > 0:
        print("HelpDesk project-aware runtime repair pass rate:", round((passed / total) * 100, 2), "%")

    print("\\nOutput file:", OUTPUT_FILE)
    print("Repair code dir:", REPAIR_DIR)
    print("Log dir:", LOG_DIR)
    print("\\nDONE")


